import React, { useState, useEffect } from 'react';
import { useNavigate } from 'react-router-dom';
import { aiAPI, faqAPI } from '../services/api';
import { useToast } from '../context/ToastContext';
import { History, Sparkles, Trash2, Save, ExternalLink } from 'lucide-react';

export default function AIHistoryPage() {
  const [history, setHistory] = useState([]);
  const [loading, setLoading] = useState(true);
  const navigate = useNavigate();
  const { showSuccess, showError } = useToast();

  useEffect(() => {
    fetchHistory();
  }, []);

  const fetchHistory = async () => {
    try {
      const res = await aiAPI.getHistory();
      setHistory(res.history || []);
    } catch (err) {
      console.error(err);
    } finally {
      setLoading(false);
    }
  };

  const handleSaveToFaq = async (item) => {
    try {
      await faqAPI.create({
        question: item.generatedQuestion,
        answer: item.generatedAnswer,
        categoryName: item.category || 'General',
        keywords: item.keywords || [],
        isAiGenerated: true
      });
      showSuccess('Saved AI FAQ to Knowledge Base!');
      navigate('/knowledge');
    } catch (err) {
      showError(err.message || 'Failed to save FAQ.');
    }
  };

  const handleDeleteHistory = async (id) => {
    try {
      await aiAPI.deleteHistory(id);
      showSuccess('History entry deleted.');
      setHistory(prev => prev.filter(h => h.id !== id));
    } catch (err) {
      showError('Failed to delete history item.');
    }
  };

  return (
    <div className="page-body animate-fade-in">
      <div style={{ marginBottom: '2rem' }}>
        <h1 style={{ fontSize: '1.8rem', fontWeight: 700, marginBottom: '0.25rem' }}>AI Generation History</h1>
        <p style={{ color: 'var(--text-secondary)', fontSize: '0.9rem' }}>
          Review, reuse, or convert previously generated AI FAQs into published knowledge base articles.
        </p>
      </div>

      {loading ? (
        <div style={{ textAlign: 'center', padding: '3rem' }}>Loading AI history...</div>
      ) : history.length === 0 ? (
        <div className="card" style={{ padding: '3rem', textAlign: 'center', color: 'var(--text-muted)' }}>
          No AI generations recorded yet. Use AI Studio to generate your first FAQ article.
        </div>
      ) : (
        <div style={{ display: 'flex', flexDirection: 'column', gap: '1rem' }}>
          {history.map(item => (
            <div key={item.id} className="card" style={{ padding: '1.25rem' }}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: '0.75rem' }}>
                <div>
                  <span className="badge badge-ai" style={{ marginBottom: '0.35rem' }}>
                    <Sparkles size={11} /> Topic: {item.topic}
                  </span>
                  <h3 style={{ fontSize: '1.1rem', fontWeight: 600, color: 'var(--text-main)' }}>
                    {item.generatedQuestion}
                  </h3>
                </div>
                <div style={{ display: 'flex', gap: '8px' }}>
                  <button onClick={() => handleSaveToFaq(item)} className="btn btn-primary" style={{ fontSize: '0.8rem', padding: '0.4rem 0.75rem' }}>
                    <Save size={14} /> Save to FAQs
                  </button>
                  <button onClick={() => handleDeleteHistory(item.id)} className="btn btn-ghost" style={{ color: 'var(--status-error)', padding: '0.4rem' }}>
                    <Trash2 size={16} />
                  </button>
                </div>
              </div>

              <div style={{
                backgroundColor: 'var(--bg-app)',
                padding: '0.85rem 1rem',
                borderRadius: '6px',
                fontSize: '0.875rem',
                color: 'var(--text-secondary)',
                lineHeight: 1.5,
                whiteSpace: 'pre-wrap',
                marginBottom: '0.75rem'
              }}>
                {item.generatedAnswer}
              </div>

              <div style={{ fontSize: '0.75rem', color: 'var(--text-muted)' }}>
                Generated by {item.createdBy || 'AI'} on {new Date(item.createdAt).toLocaleString()}
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
